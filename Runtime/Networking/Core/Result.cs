namespace SS.Utilities.Networking
{
    /// <summary>
    /// Encapsulates the outcome of an asynchronous network operation, 
    /// providing transport status codes, payload data, and display messages 
    /// while avoiding unnecessary heap allocations during evaluation.
    /// </summary>
    public readonly struct Result<T>
    {
        /// <summary>
        /// Indicates whether the network transaction completed with a successful HTTP status code.
        /// </summary>
        public bool IsSuccess => Status >= 200 && Status < 300;

        /// <summary>
        /// The raw HTTP status code returned by the server or generated by client-side transport faults.
        /// </summary>
        public long Status { get; }

        /// <summary>
        /// Optional descriptive text reserved exclusively for UI presentation, debugging, or logging.
        /// </summary>
        public string Message { get; }

        /// <summary>
        /// The strongly-typed data payload parsed from the response body.
        /// </summary>
        public T Data { get; }

        public Result(long status, T data, string message = null)
        {
            Status = status;
            Data = data;
            Message = message;
        }
    }
}